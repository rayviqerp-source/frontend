interface TicketSeedInput {
  n: number;
  oemId: string;
  status: TicketStatus;
  priority: Ticket["priority"];
  customerId: string;
  siteId: string;
  equipmentId?: string;
  createdAt: string;
  updatedAt: string;
  source?: Ticket["source"];
  category: string;
  categoryGroup: Ticket["issue"]["categoryGroup"];
  description: string;
  errorCode?: string;
  createdBy: string;
  assignedEngineerId?: string;
  reportId?: string;
  closedAt?: string;
  contact?: Partial<Ticket["contact"]>;
  timeline: TimelineEvent[];
  notes?: InternalNoteSeed[];
  attachments?: TicketAttachment[];
  breached?: boolean;
}

interface InternalNoteSeed {
  author: string;
  body: string;
  at: string;
  visibility: "oem_internal" | "platform_internal";
}

const RESOLUTION_HOURS: Record<Ticket["priority"], number> = {
  critical: 24,
  high: 48,
  medium: 96,
  low: 168,
};

function makeTicket(input: TicketSeedInput): Ticket {
  const site = seedSites.find((s) => s.id === input.siteId)!;
  const customer = seedCustomers.find((c) => c.id === input.customerId)!;
  const equipment = input.equipmentId
    ? seedEquipment.find((e) => e.id === input.equipmentId)
    : undefined;
  const priority = input.priority;
  const responseDue = addMinutes(input.createdAt, 60);
  const assignmentDue = addHours(input.createdAt, 4);
  const visitDue = addHours(input.createdAt, RESOLUTION_HOURS[priority] / 2);
  const resolutionDue = addHours(input.createdAt, RESOLUTION_HOURS[priority]);
  seq += 1;
  return {
    id: `TKT-${String(input.n).padStart(4, "0")}`,
    ref: nextTicketRef(input.n),
    oemId: input.oemId,
    status: input.status,
    priority,
    createdAt: input.createdAt,
    updatedAt: input.updatedAt,
    dueAt: resolutionDue,
    source: input.source ?? "portal",
    customerId: input.customerId,
    siteId: input.siteId,
    equipmentId: input.equipmentId,
    contact: {
      name: customer.name,
      phone: customer.phone,
      email: customer.email,
      company: customer.company ?? customer.name,
      availability: input.contact?.availability ?? "Weekdays 10:00 – 18:00",
      ...input.contact,
    },
    location: {
      address: site.address,
      state: site.state,
      city: site.city,
      pincode: site.pincode,
      gps: site.gps,
    },
    product: {
      model: equipment?.model ?? "VTX-3P-60K",
      serialNumber: equipment?.serialNumber ?? "—",
      category: equipment?.category ?? "string_inverter",
      installationDate: equipment?.installationDate,
      warrantyStatus: equipment
        ? equipment.warrantyEndsOn > "2026-11-02"
          ? input.status === "closed" || input.status === "completed"
            ? "in_warranty"
            : "in_warranty"
          : "out_of_warranty"
        : "unknown",
      amcId: site.amcId,
    },
    issue: {
      category: input.category,
      description: input.description,
      errorCode: input.errorCode,
      categoryGroup: input.categoryGroup,
    },
    assignedEngineerId: input.assignedEngineerId,
    sla: {
      responseDueAt: responseDue,
      assignmentDueAt: assignmentDue,
      visitDueAt: visitDue,
      resolutionDueAt: resolutionDue,
      breached: input.breached ?? false,
    },
    attachments: input.attachments ?? [],
    timeline: input.timeline,
    notes: (input.notes ?? []).map((n, i) => ({
      id: `NOTE-${input.n}-${i + 1}`,
      ...n,
    })),
    reportId: input.reportId,
    escalationIds: [],
    closedAt: input.closedAt,
    createdBy: input.createdBy,
  };
}

