"use client";

import { useMemo, useState } from "react";
import { Bell, CheckCheck, Filter, Inbox } from "lucide-react";
import { useStore, unreadCount } from "@/lib/store";
import { ROLE_LABELS } from "@/lib/constants";
import { relativeTime } from "@/lib/utils";
import { PageHeader, Card } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { EmptyState } from "@/components/ui/states";
import { Tabs } from "@/components/ui/tabs";

export default function NotificationsPage() {
  const { state, markNotificationRead, markAllNotificationsRead, clearNotifications, effectiveRole, toast } =
    useStore();
  const uid = state.currentUserId ?? "USR-08";
  const [tab, setTab] = useState<"all" | "unread" | "mine">("all");

  const filtered = useMemo(() => {
    let list = state.notifications;
    if (tab === "unread") list = list.filter((n) => !n.readBy.includes(uid));
    if (tab === "mine")
      list = list.filter(
        (n) =>
          n.audience.includes(effectiveRole) ||
          n.engineerId === state.users.find((u) => u.id === uid)?.engineerId,
      );
    return list;
  }, [state.notifications, state.users, uid, tab, effectiveRole]);

  const unread = unreadCount(state);

  return (
    <div className="mx-auto max-w-4xl">
      <PageHeader
        title="Notification centre"
        description="In-app notifications generated by ticket, assignment, visit and report events. Email/SMS/WhatsApp channels are configured but not delivered in this demo."
        actions={
          <>
            <Button
              variant="outline"
              onClick={() => {
                markAllNotificationsRead();
              }}
              disabled={unread === 0}
            >
              <CheckCheck className="h-4 w-4" /> Mark all read
            </Button>
            <Button
              variant="ghost"
              onClick={() => {
                clearNotifications();
              }}
              disabled={state.notifications.length === 0}
            >
              Clear
            </Button>
          </>
        }
      />

      <Tabs
        active={tab}
        onChange={(k) => setTab(k as typeof tab)}
        tabs={[
          { key: "all", label: "All", count: state.notifications.length },
          { key: "unread", label: "Unread", count: unread },
          { key: "mine", label: "For my role", count: state.notifications.filter((n) => n.audience.includes(effectiveRole)).length },
        ]}
        className="mb-4"
      />

      {filtered.length === 0 ? (
        <EmptyState
          icon={<Inbox className="h-5 w-5" />}
          title="Nothing to show"
          description="Notifications for this filter will appear here as tickets move through their lifecycle."
        />
      ) : (
        <ul className="space-y-2.5">
          {filtered.map((n) => {
            const isUnread = !n.readBy.includes(uid);
            return (
              <li key={n.id}>
                <Card
                  className={`p-4 transition-colors ${isUnread ? "border-brand-200 bg-brand-50/40" : ""}`}
                >
                  <div className="flex items-start gap-3">
                    <span
                      className={`mt-1 flex h-8 w-8 shrink-0 items-center justify-center rounded-lg ${
                        isUnread ? "bg-brand-100 text-brand-700" : "bg-surface-alt text-ink-faint"
                      }`}
                    >
                      <Bell className="h-4 w-4" />
                    </span>
                    <div className="min-w-0 flex-1">
                      <div className="flex flex-wrap items-center gap-2">
                        <p className={`text-sm ${isUnread ? "font-semibold text-ink" : "font-medium text-ink-soft"}`}>
                          {n.title}
                        </p>
                        {isUnread && <Badge tone="blue">New</Badge>}
                        {n.ticketRef && (
                          <span className="font-mono text-xs text-brand-600">{n.ticketRef}</span>
                        )}
                      </div>
                      <p className="mt-1 text-[13px] leading-6 text-ink-muted">{n.body}</p>
                      <div className="mt-2 flex flex-wrap items-center gap-2 text-xs text-ink-faint">
                        <span>{relativeTime(n.createdAt)}</span>
                        <span>·</span>
                        <span>{n.audience.map((r) => ROLE_LABELS[r]).join(", ")}</span>
                      </div>
                      <div className="mt-2 flex flex-wrap gap-1.5">
                        {n.channels.map((c) => (
                          <Badge
                            key={c}
                            tone={
                              c === "in_app"
                                ? "blue"
                                : n.delivery === "delivered"
                                  ? "green"
                                  : n.delivery === "failed"
                                    ? "red"
                                    : "gray"
                            }
                          >
                            {c.replace(/_/g, " ")}
                            {c !== "in_app" ? ` · ${n.delivery.replace(/_/g, " ")}` : ""}
                          </Badge>
                        ))}
                      </div>
                    </div>
                    <div className="flex shrink-0 flex-col items-end gap-2">
                      {!isUnread ? (
                        <Badge tone="gray">Read</Badge>
                      ) : (
                        <Button
                          size="sm"
                          variant="outline"
                          onClick={() => markNotificationRead(n.id)}
                        >
                          Mark read
                        </Button>
                      )}
                    </div>
                  </div>
                </Card>
              </li>
            );
          })}
        </ul>
      )}

      <Card className="mt-5 p-4">
        <p className="flex items-start gap-2 text-[13px] leading-6 text-ink-muted">
          <Filter className="mt-0.5 h-4 w-4 shrink-0 text-ink-faint" />
          Delivery states (<strong className="font-medium text-ink-soft">delivered</strong>,{" "}
          <strong className="font-medium text-ink-soft">queued</strong>,{" "}
          <strong className="font-medium text-ink-soft">skipped_no_provider</strong>) are simulated.
          Connect an email/SMS/WhatsApp provider via{" "}
          <a href="/admin/integrations" className="font-medium text-brand-600 hover:underline">
            Integrations
          </a>{" "}
          once the backend exists. If you see a toast, the interaction worked:{" "}
          <Button
            size="sm"
            variant="ghost"
            onClick={() => toast("This is how RAYVIQ toasts appear", { tone: "info" })}
          >
            test toast
          </Button>
        </p>
      </Card>
    </div>
  );
}
